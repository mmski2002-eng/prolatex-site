<h2>Что означают сертификаты GOLS и OEKO-TEX</h2>

<p>GOLS (Global Organic Latex Standard) — международный стандарт, подтверждающий, что латекс произведён из органически выращенного каучука с соблюдением экологических и социальных норм на всей цепочке производства, от плантации до готового блока.</p>

<p>OEKO-TEX Standard 100 — независимая проверка готового текстильного или пенного изделия на содержание вредных для здоровья веществ; сертификат не говорит о происхождении сырья, а именно о безопасности конечного продукта.</p>

<p>Наличие обоих сертификатов на конкретную модель — более надёжный аргумент в пользу «натуральности», чем формулировка «100% натуральный латекс» в описании товара без документов.</p>


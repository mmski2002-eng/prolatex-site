<h3>Высокая цена</h3>

<p>Натуральный латекс дороже ППУ и большинства пружинных матрасов — это следствие более сложного и энергозатратного производства (особенно метод Talalay) и стоимости самого сырья. Разброс цен на рынке большой и зависит от процента натурального латекса, конструкции (монолитный блок, комбинация с пружинами или кокосовой койрой) и бренда, поэтому единую цифру называть некорректно — цену конкретной модели нужно смотреть в каталоге производителя.</p>

<h3>Вес матраса</h3>

<p>Латекс плотнее большинства наполнителей, поэтому латексные матрасы заметно тяжелее пружинных или ППУ-аналогов того же размера. Это усложняет переворачивание, транспортировку и самостоятельную установку — особенно для матрасов от 160 см в ширину.</p>

<h3>Специфическая упругость</h3>

<p>Латекс не «обволакивает» тело так, как медленно реагирующая пена с эффектом памяти (memory foam) — вместо этого он быстро выталкивает обратно. Для одних это плюс (легче менять позу во сне, не «тонешь»), для других — минус, если привычен именно эффект памяти.</p>

